function importDataFromFile(file) {
  if (!file) return;
  const reader = new FileReader();
  reader.onload = () => {
    try {
      const parsed = JSON.parse(String(reader.result || ""));
      const nextState = parsed && parsed.data && typeof parsed.data === "object" ? parsed.data : parsed;
      if (!nextState || Array.isArray(nextState) || typeof nextState !== "object") throw new Error("檔案格式不正確");
      state = nextState;
      saveState();
      if (parsed && parsed.currentView && parsed.currentView.term && parsed.currentView.exam) {
        selectedTerm = parsed.currentView.term;
        selectedExam = parsed.currentView.exam;
        selectedSubject = normalizeSubjectForTerm(parsed.currentView.subject || selectedSubject, selectedTerm, selectedExam);
      }
      pageByPlan = {};
      setBackupStatus("匯入成功", "ok");
      render();
    } catch (error) {
      setBackupStatus("匯入失敗：檔案格式不正確", "error");
    }
  };
  reader.onerror = () => setBackupStatus("匯入失敗：無法讀取檔案", "error");
  reader.readAsText(file, "utf-8");
}

