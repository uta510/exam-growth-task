async function pushCloudState(options = {}) {
  if (!cloudClient || !cloudUser) return false;
  cloudSyncing = true;
  if (!options.silent) {
    setCloudStatus("正在上傳雲端...", "syncing");
    setCloudDialogStatus("正在上傳雲端...");
  }
  try {
    const payload = {
      user_id: cloudUser.id,
      data: completeStateSnapshot(),
      current_view: currentViewData(),
      app_version: storageKey
    };
    const { error } = await cloudClient
      .from("review_app_state")
      .upsert(payload, { onConflict: "user_id" });
    if (error) throw error;
    setCloudStatus("雲端已同步", "ok");
    if (!options.silent) setCloudDialogStatus("已上傳本機資料到雲端", "ok");
    return true;
  } catch (error) {
    setCloudStatus("雲端同步失敗", "error");
    if (!options.silent) setCloudDialogStatus(cloudErrorMessage(error), "error");
    return false;
  } finally {
    cloudSyncing = false;
  }
}
async function pullCloudState(options = {}) {
  if (!cloudClient || !cloudUser) return false;
  cloudSyncing = true;
  setCloudStatus("正在讀取雲端...", "syncing");
  if (!options.silent) setCloudDialogStatus("正在讀取雲端...");
  try {
    const { data, error } = await cloudClient
      .from("review_app_state")
      .select("data,current_view,updated_at")
      .eq("user_id", cloudUser.id)
      .maybeSingle();
    if (error) throw error;
    if (!data || !data.data) {
      cloudSyncing = false;
      await pushCloudState({ silent: options.silent });
      if (!options.silent) setCloudDialogStatus("雲端尚無資料，已先上傳目前這份", "ok");
      return true;
    }
    cloudApplyingRemote = true;
    state = data.data && typeof data.data === "object" && !Array.isArray(data.data) ? data.data : {};
    localStorage.setItem(storageKey, JSON.stringify(state));
    if (data.current_view && data.current_view.term && data.current_view.exam) {
      selectedTerm = data.current_view.term;
      selectedExam = data.current_view.exam;
      selectedSubject = normalizeSubjectForTerm(data.current_view.subject || selectedSubject, selectedTerm, selectedExam);
    }
    pageByPlan = {};
    render();
    setCloudStatus("雲端已同步", "ok");
    if (!options.silent) setCloudDialogStatus("已下載雲端資料", "ok");
    return true;
  } catch (error) {
    setCloudStatus("雲端同步失敗", "error");
    if (!options.silent) setCloudDialogStatus(cloudErrorMessage(error), "error");
    return false;
  } finally {
    cloudApplyingRemote = false;
    cloudSyncing = false;
  }
}
