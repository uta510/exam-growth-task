function normalizeSupabaseProjectUrl(value) {
  const text = String(value || "").trim();
  if (!text) return "";
  try {
    const url = new URL(text);
    return url.origin;
  } catch {
    return text.replace(/\/rest\/v1\/?$/i, "").replace(/\/+$/, "");
  }
}
