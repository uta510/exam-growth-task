function configureCloudClient() {
  const config = loadCloudConfig();
  if (!config.projectUrl || !config.anonKey) {
    cloudClient = null;
    cloudUser = null;
    setCloudStatus("雲端尚未設定");
    return null;
  }
  if (!window.supabase || typeof window.supabase.createClient !== "function") {
    cloudClient = null;
    setCloudStatus("雲端套件尚未載入", "error");
    return null;
  }
  cloudClient = window.supabase.createClient(config.projectUrl, config.anonKey, {
    auth: {
      persistSession: true,
      autoRefreshToken: true,
      storageKey: storageKey + "-supabase-auth"
    }
  });
  return cloudClient;
}
