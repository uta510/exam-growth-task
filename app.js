function getTasks(subject, exam, term = selectedTerm) {
  const key = planKey(subject, exam, term);
  const legacyKey = legacyPlanKey(subject, exam);
  if (shouldClearTaskList(term, exam)) {
    let changed = false;
    if (!Array.isArray(state[key]) || state[key].length) {
      state[key] = [];
      changed = true;
    }
    if (state._customTasks && state._customTasks[key]) {
      delete state._customTasks[key];
      changed = true;
    }
    if (!state._signatures) state._signatures = {};
    if (state._signatures[key] !== "") {
      state._signatures[key] = "";
      changed = true;
    }
    if (changed) saveState();
    return state[key];
  }
  if (state._customTasks && state._customTasks[key] && Array.isArray(state[key])) {
    state[key] = state[key].map((task, index) => normalizeTask(task, key, index));
    return state[key];
  }
  const freshTasks = makeTasks(subject, exam, term);
  const signature = taskSignature(freshTasks);
  if (!state._signatures) state._signatures = {};
  const currentSignature = Array.isArray(state[key]) ? taskSignature(state[key]) : "";
  if (!state[key] || state._signatures[key] !== signature || currentSignature !== signature) {
    const oldTasks = Array.isArray(state[key]) ? state[key] : term === "七年級下學期" && Array.isArray(state[legacyKey]) ? state[legacyKey] : [];
    state[key] = freshTasks.map((task, index) => {
      const oldTask = oldTasks.find((item) => item.id === task.id) || oldTasks.find((item) => item.title === task.title) || oldTasks[index];
      return oldTask ? { ...task, done: Boolean(oldTask.done), date: oldTask.date || "", note: oldTask.note || "", noteOrder: oldTask.noteOrder || 0, noteDone: Boolean(oldTask.noteDone), noteDoneDate: oldTask.noteDoneDate || "" } : { ...task, note: task.note || "", noteOrder: task.noteOrder || 0, noteDone: false, noteDoneDate: "" };
    });
    state._signatures[key] = signature;
    saveState();
  }
  return state[key];
}
